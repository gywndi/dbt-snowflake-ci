-- dbt 배포용 Snowflake 초기 구성 전체. 아무것도 없는 상태에서 관리자 연결(ACCOUNTADMIN)로 한 번 실행한다.
--   snow sql -c admin -f setup/01-dbt-setup.sql -D svc_dbt_password="<비밀번호>"
-- 구조: 원천(SNOWFLAKE_SAMPLE_DATA, 사용자 접근 X) -> DBT_APP -> DBT_PROD.MART 뷰 -> DBT_USER(사용자 접근 O)
--   DBT_APP  : dbt 애플리케이션이 쓰는 롤 (SVC_DBT 계정이 사용)
--   DBT_USER : 결과 뷰를 조회하는 사용자 롤 (조회 계정은 나중에 만들어 이 롤만 부여)
-- CI 한 바퀴 검증용으로 SVC_DBT는 비밀번호 인증을 쓴다. 완성 단계에서는 키페어(TYPE = SERVICE)로 바꾼다.

USE ROLE ACCOUNTADMIN;

-- 롤
CREATE ROLE IF NOT EXISTS DBT_APP;
CREATE ROLE IF NOT EXISTS DBT_USER;

-- 웨어하우스: 가장 작은 크기, 60초 유휴 시 자동 중지
CREATE WAREHOUSE IF NOT EXISTS DBT_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

GRANT USAGE ON WAREHOUSE DBT_WH TO ROLE DBT_APP;
GRANT USAGE ON WAREHOUSE DBT_WH TO ROLE DBT_USER;

-- 원천 읽기: 샘플 데이터는 공유(Share) DB라 USAGE/SELECT 대신 IMPORTED PRIVILEGES를 준다
-- 계정에 이 DB가 없으면 먼저: CREATE DATABASE SNOWFLAKE_SAMPLE_DATA FROM SHARE SFC_SAMPLES.SAMPLE_DATA;
GRANT IMPORTED PRIVILEGES ON DATABASE SNOWFLAKE_SAMPLE_DATA TO ROLE DBT_APP;

-- 개발: dbt가 스키마를 직접 만든다 (소유자는 DBT_APP)
CREATE DATABASE IF NOT EXISTS DBT_DEV;
GRANT USAGE ON DATABASE DBT_DEV TO ROLE DBT_APP;
GRANT CREATE SCHEMA ON DATABASE DBT_DEV TO ROLE DBT_APP;

-- 운영: 스키마는 관리자가 미리 만들고, DBT_APP은 뷰만 만든다
CREATE DATABASE IF NOT EXISTS DBT_PROD;
CREATE SCHEMA IF NOT EXISTS DBT_PROD.MART;
GRANT USAGE ON DATABASE DBT_PROD TO ROLE DBT_APP;
GRANT USAGE ON SCHEMA DBT_PROD.MART TO ROLE DBT_APP;
GRANT CREATE VIEW ON SCHEMA DBT_PROD.MART TO ROLE DBT_APP;

-- 사용자: 결과 뷰 조회만. FUTURE 권한이라 dbt가 뷰를 다시 만들어도 자동으로 붙는다
GRANT USAGE ON DATABASE DBT_PROD TO ROLE DBT_USER;
GRANT USAGE ON SCHEMA DBT_PROD.MART TO ROLE DBT_USER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA DBT_PROD.MART TO ROLE DBT_USER;

-- 애플리케이션 계정: LEGACY_SERVICE는 사람이 아닌 계정이면서 비밀번호 인증을 허용한다
CREATE USER IF NOT EXISTS SVC_DBT
  TYPE = LEGACY_SERVICE
  PASSWORD = '<% svc_dbt_password %>'
  DEFAULT_ROLE = DBT_APP
  DEFAULT_WAREHOUSE = DBT_WH
  COMMENT = 'dbt 배포용 서비스 계정';

GRANT ROLE DBT_APP TO USER SVC_DBT;

-- 확인
SHOW GRANTS TO ROLE DBT_APP;
SHOW GRANTS TO ROLE DBT_USER;
SHOW GRANTS TO USER SVC_DBT;
