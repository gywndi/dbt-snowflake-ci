-- 뷰 외에 테이블·다이내믹 테이블을 쓰기 위한 추가 권한. 관리자 연결(ACCOUNTADMIN)로 실행한다.

USE ROLE ACCOUNTADMIN;

-- dbt(DBT_APP)가 운영 스키마에 테이블과 다이내믹 테이블을 만들 수 있게 한다
GRANT CREATE TABLE ON SCHEMA DBT_PROD.MART TO ROLE DBT_APP;
GRANT CREATE DYNAMIC TABLE ON SCHEMA DBT_PROD.MART TO ROLE DBT_APP;

-- 사용자(DBT_USER)가 새로 생기는 테이블과 다이내믹 테이블도 조회할 수 있게 한다
GRANT SELECT ON FUTURE TABLES IN SCHEMA DBT_PROD.MART TO ROLE DBT_USER;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA DBT_PROD.MART TO ROLE DBT_USER;

-- 확인
SHOW GRANTS TO ROLE DBT_APP;
SHOW FUTURE GRANTS IN SCHEMA DBT_PROD.MART;
